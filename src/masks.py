def get_mask_card_number(card_str: int | str) -> str:
    """Маскирует номер банковской карты по шаблону «XXXX XX** **** XXXX».

    Функция принимает номер карты (как число или строку), проверяет, что он содержит
    ровно 16 цифр, и возвращает маску, скрывающую средние цифры.

    Шаблон маски:
    - первые 4 цифры видны полностью;
    - следующие 2 цифры видны, затем идёт «**»;
    - далее «****» (полностью скрытые цифры);
    - последние 4 цифры видны.

    Args:
        card_str (int | str): Номер карты. Может быть передан как целое число
            или строка. Пробелы, дефисы и прочие нецифровые символы
            не допускаются (вызовут ошибку длины).

    Returns:
        str: Маска номера карты в формате «1234 56** **** 7890».

    Raises:
        ValueError: Если длина номера карты не равна 16 цифрам.

    Examples:
        >>> get_mask_card_number(1234567890123456)
        '1234 56** **** 3456'

        >>> get_mask_card_number("1234567890123456")
        '1234 56** **** 3456'

        >>> get_mask_card_number("1234")
        Traceback (most recent call last):
            ...
        ValueError: Номер карты должен содержать 16 цифр.
    """

    card_str = str(card_str)

    if len(card_str) != 16:
        raise ValueError("Номер карты должен содержать 16 цифр.")

    formatted_number_card = f"{card_str[:4]} {card_str[4:6]}** **** {card_str[-4:]}"
    return formatted_number_card


def get_mask_account(score_str: int | str) -> str:
    """Маскирует номер счёта по шаблону «**XXXX».

    Функция принимает номер счёта (как число или строку) и возвращает маску,
    содержащую только последние 4 цифры, предварённые двумя звёздочками.

    Args:
        score_str (int | str): Номер счёта. Может быть передан как целое число
            или строка. Пробелы, дефисы и прочие нецифровые символы
            не допускаются (будут включены в длину строки).

    Returns:
        str: Маска номера счёта в формате «**7890», где «7890» —
            последние 4 цифры исходного номера.

    Notes:
        - Если в номере счёта меньше 4 цифр, маска всё равно будет содержать
          последние имеющиеся цифры (например, для «12» вернётся «**12»).
        - Функция не проверяет смысловую корректность номера счёта,
          только форматирует последние 4 символа.

    Examples:
        >>> get_mask_account(987654321)
        '**4321'

        >>> get_mask_account("12345678")
        '**5678'

        >>> get_mask_account("12")
        '**12'
    """
    score_str = str(score_str)

    mask_account = f"**{score_str[-4:]}"
    return mask_account
